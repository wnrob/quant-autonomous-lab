"""Turn artifacts/futures/real_data_audit.json into the data-gap report (data_gap.md + data_gap.json). Descriptive only.

    envs/core/bin/python -m engine.futures.gap_report
"""
from __future__ import annotations
import json
from pathlib import Path

OUT = Path(__file__).resolve().parents[2] / "artifacts" / "futures"


def build(audit: dict) -> dict:
    daily = audit["daily"]
    per_root = []
    for d in daily:
        c = d["stale"]["counts"]; p = d.get("roll_gap_proxy", {})
        per_root.append({
            "root": d["root"], "rows": d["rows"], "first_trade_date": d["first"], "last_trade_date": d["last"],
            "n_rolls": d["n_rolls"], "rolls_abs_z_gt_2": d["rolls_abs_z_gt_2"], "rolls_abs_z_gt_3": d["rolls_abs_z_gt_3"],
            "median_abs_roll_gap_logret": d["median_abs_gap_logret"],
            "roll_bdays_before_ref": d["roll_bdays_before_roll_ref"],
            "missing_business_days": d["missing_business_days"], "missing_examples": d["missing_examples"],
            "label_collisions": d["trade_date_collisions"],
            "back_switches": c.get("back_switch", 0), "past_last_trade_rows": c.get("past_last_trade", 0),
            "thin_segment_rows": c.get("thin_segment", 0), "days_before_panel_end": c.get("days_before_panel_end"),
            "errors": [f["check"] for f in d["stale"]["flags"] if f["severity"] == "error"],
            "error_examples": {f["check"]: f["examples"][:2] for f in d["stale"]["flags"] if f["severity"] == "error"},
            "naive_pctchange_roll_day_share_of_abs_return": d["naive_pctchange_roll_days"]["share_of_total_abs_ret"],
            "naive_pctchange_max_roll_day_abs_return": d["naive_pctchange_roll_days"]["max_abs_roll_day_ret"],
            "roll_gap_proxy_ann": p.get("implied_ann_roll_yield_mean"), "roll_gap_proxy_se": p.get("noise_se_ann"),
            "roll_gap_proxy_distinguishable": p.get("distinguishable_from_zero"),
        })
    intr = [{"file": d["file"], "rows": d["rows"], "contracts": d["contracts"], "errors": [f["check"] for f in d["stale"]["flags"] if f["severity"] == "error"],
             "back_switches": d["stale"]["counts"].get("back_switch", 0), "multi_contract": d["stale"]["counts"].get("multi_contract_timestamp", 0),
             "thin_segment_rows": d["stale"]["counts"].get("thin_segment", 0)} for d in audit["intraday"]]
    return {
        "verdict": "REAL CARRY / ROLL YIELD NOT COMPUTABLE from the local data",
        "why": ["every file is ONE spliced front-month series (one contract per row, `contract` column) - no per-contract price history",
                "no date has two contracts observed together, so front-vs-next spread and a proper back-adjustment cannot be formed",
                "the user's pipeline fetched per-contract bars (qa/daily.py load_product) but cached only the splice"],
        "series_type": "unadjusted spliced front month, chosen by same-day volume with a forward-only ratchet (qa/roll.py active_by_date); NOT back-adjusted",
        "date_label_issue": "daily bars are stamped with the vendor session window_start date: Sun-Thu labels = NEXT business day's session (MES label 2024-09-12 closes 5626.50 = 2024-09-13 session). Mapped heuristically; grain post-holiday daytime sessions and the last row are exceptions; collisions reported, not merged",
        "protected_era": audit["protected_era_note"],
        "what_is_needed": ["per-contract daily (or 1m) OHLCV for at least front + next contract of each root, on the same dates",
                           "ideally per-contract open interest, for an OI-crossover roll rule",
                           "a session/trade-date field from the vendor instead of window_start"],
        "per_root": per_root, "intraday": intr,
    }


def to_md(g: dict) -> str:
    L = ["# Futures data-gap report (generated by engine/futures/gap_report.py)", "",
         f"**{g['verdict']}.**", ""] + [f"- {w}" for w in g["why"]] + [
         "", f"Series type: {g['series_type']}.", "", f"Date labels: {g['date_label_issue']}.", "",
         f"Protected era: {g['protected_era']}.", "",
         "## Per root (daily files, trade-date basis)", "",
         "| root | rows | last | rolls | \\|z\\|>3 gaps | roll bdays before ref | missing bdays | thin-segment rows | stale days | errors | roll-gap proxy ann (se) |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in g["per_root"]:
        px = f"{r['roll_gap_proxy_ann']:+.3f} ({r['roll_gap_proxy_se']:.3f})" if r["roll_gap_proxy_ann"] is not None else "-"
        L.append(f"| {r['root']} | {r['rows']} | {r['last_trade_date']} | {r['n_rolls']} | {r['rolls_abs_z_gt_3']} | {r['roll_bdays_before_ref']} | "
                 f"{r['missing_business_days']} | {r['thin_segment_rows']} | {r['days_before_panel_end']} | {', '.join(r['errors']) or '-'} | {px} |")
    L += ["", "Roll-gap proxy = -(ln new(t) - ln old(t-1)) x 365 / days between expiries, averaged over rolls. Each gap mixes the calendar "
          "spread with one day of market noise, so it is a NOISY PROXY with the stated SE, not a carry measurement. Positive = backwardation.",
          "'roll bdays before ref' = business days between the actual (volume) roll and the old contract's reference date (first notice for "
          "physically delivered metals/rates/grains, else last trade).", "", "## Error details", ""]
    for r in g["per_root"]:
        for k, ex in r["error_examples"].items(): L.append(f"- {r['root']} `{k}`: {ex}")
    L += ["", "## Intraday 1m caches", "", "| file | rows | contracts | back switches | multi-contract ts | thin-segment rows (>=390 bars) | errors |", "|---|---|---|---|---|---|---|"]
    for d in g["intraday"]:
        L.append(f"| {d['file']} | {d['rows']} | {len(d['contracts'])} | {d['back_switches']} | {d['multi_contract']} | {d['thin_segment_rows']} | {', '.join(d['errors']) or '-'} |")
    L += ["", "## What is needed for real carry", ""] + [f"- {w}" for w in g["what_is_needed"]]
    return "\n".join(L) + "\n"


def main():
    audit = json.loads((OUT / "real_data_audit.json").read_text())
    g = build(audit)
    (OUT / "data_gap.json").write_text(json.dumps(g, indent=2, default=str))
    (OUT / "data_gap.md").write_text(to_md(g))
    return g


if __name__ == "__main__":
    main()
